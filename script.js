function ensureInquiryDialog() {
  let dialog = document.querySelector("#inquiryDialog");
  if (dialog) return dialog;

  document.body.insertAdjacentHTML(
    "beforeend",
    `
      <dialog class="inquiry-dialog" id="inquiryDialog">
        <button class="inquiry-close" type="button" aria-label="Zatvori">×</button>
        <div class="inquiry-dialog-panel"></div>
      </dialog>
    `,
  );

  dialog = document.querySelector("#inquiryDialog");
  dialog.addEventListener("click", (event) => {
    if (event.target === dialog) dialog.close();
  });
  dialog.querySelector(".inquiry-close").addEventListener("click", () => dialog.close());
  return dialog;
}

function openInquiryDialog(kittenName) {
  const labels = tr().inquiry;
  const dialog = ensureInquiryDialog();
  const panel = dialog.querySelector(".inquiry-dialog-panel");

  panel.innerHTML = `
    <form class="inquiry-form" data-kitten="${kittenName}">
      <div class="inquiry-heading">
        <span class="status">${kittenName}</span>
        <h2>${labels.open}</h2>
      </div>
      <label>
        ${labels.name}
        <input name="name" type="text" autocomplete="name" required />
      </label>
      <label>
        ${labels.email}
        <input name="email" type="email" autocomplete="email" required />
      </label>
      <label>
        ${labels.message}
        <textarea name="message" rows="5" required>${labels.defaultMessage(kittenName)}</textarea>
      </label>
      <button class="button primary" type="submit">${labels.submit}</button>
      <p class="form-status" role="status"></p>
    </form>
  `;

  dialog.showModal();
  panel.querySelector("input")?.focus();
}

function moveDetailSlider(button) {
  const slider = button.closest(".detail-slider");
  const track = slider?.querySelector(".detail-slider-track");
  if (!track) return;

  const direction = Number(button.dataset.slideDirection || 1);
  moveSliderTrack(track, direction);
}

function moveSliderTrack(track, direction = 1) {
  const slideCount = track.children.length;
  if (slideCount < 2) return;

  const now = Date.now();
  if (now < Number(track.dataset.clickLockUntil || 0)) return;
  track.dataset.clickLockUntil = String(now + 650);

  const currentIndex = Number(track.dataset.currentSlide || 0);
  const nextIndex = direction > 0
    ? (currentIndex + 1) % slideCount
    : (currentIndex - 1 + slideCount) % slideCount;

  setActiveSliderImage(track, nextIndex);
}

function setActiveSliderImage(track, index) {
  const slideCount = track.children.length;
  const activeIndex = ((index % slideCount) + slideCount) % slideCount;
  track.classList.add("has-active");
  track.dataset.currentSlide = String(activeIndex);
  Array.from(track.children).forEach((slide, slideIndex) => {
    slide.classList.toggle("is-active", slideIndex === activeIndex);
  });
}

function initDetailSliders() {
  document.querySelectorAll(".detail-slider-track").forEach((track) => {
    if (track.dataset.sliderReady === "true") return;
    track.dataset.sliderReady = "true";
    setActiveSliderImage(track, 0);
  });
}

async function submitInquiry(form) {
  const status = form.querySelector(".form-status");
  const submit = form.querySelector("button[type='submit']");
  const payload = {
    kitten: form.dataset.kitten,
    name: form.elements.name.value,
    email: form.elements.email.value,
    message: form.elements.message.value,
  };

  if (status) status.textContent = tr().inquiry.sending;
  submit.disabled = true;

  try {
    const response = await fetch("/api/inquiry", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload),
    });
    const result = await response.json();
    if (!response.ok) throw new Error(result.error || tr().inquiry.error);
    form.reset();
    if (status) {
      status.textContent = result.sent
        ? tr().inquiry.sent
        : tr().inquiry.saved;
    }
  } catch (error) {
    if (status) status.textContent = error.message;
  } finally {
    submit.disabled = false;
  }
}

async function submitContactForm(form) {
  const labels = tr().pages.contactForm;
  const status = form.querySelector(".form-status");
  const submit = form.querySelector("button[type='submit']");
  const payload = {
    kitten: "Kontakt forma",
    name: form.elements.name.value,
    email: form.elements.email.value,
    message: form.elements.message.value,
  };

  if (status) status.textContent = labels.sending;
  submit.disabled = true;

  try {
    const response = await fetch("/api/inquiry", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload),
    });
    const result = await response.json();
    if (!response.ok) throw new Error(result.error || labels.error);
    form.reset();
    if (status) status.textContent = result.sent ? labels.sent : labels.saved;
  } catch (error) {
    if (status) status.textContent = error.message || labels.error;
  } finally {
    submit.disabled = false;
  }
}

function renderPostDetail() {
  const target = document.querySelector("#postDetail");
  if (!target) return;

  const id = Number(new URLSearchParams(window.location.search).get("id"));
  const post = localizeItem(posts.find((item) => Number(item.id) === id) || posts[0]);

  if (!post) {
    target.innerHTML = `<section class="page-hero"><h1>Post nije pronađen</h1><p>Vratite se na blog.</p></section>`;
    return;
  }

  const blocks = postContentBlocks(post)
    .map((block) => {
      if (block.type === "media") {
        const media = (block.items || []).map((src) => mediaMarkup(src, post.title, { controls: true })).join("");
        return media ? `<div class="detail-gallery post-media-block">${media}</div>` : "";
      }
      return `<div class="post-text-block">${postTextMarkup(block.text)}</div>`;
    })
    .join("");

  document.title = `${post.title} | Matriks Cattery`;
  target.innerHTML = `
    <article class="post-detail">
      <a class="back-link" href="blog.html">${tr().common.backBlog}</a>
      <span class="meta">${post.date || post.category || tr().common.blogFallback}</span>
      <h1>${post.title}</h1>
      ${blocks}
    </article>
  `;
}

document.addEventListener("click", async (event) => {
  const frameMenuToggle = event.target.closest(".frame-menu-toggle");
  if (frameMenuToggle) {
    const topbar = frameMenuToggle.closest(".hero-topline, .frame-topline");
    const isOpen = topbar?.classList.toggle("is-menu-open") || false;
    frameMenuToggle.setAttribute("aria-expanded", String(isOpen));
    return;
  }

  const frameNavLink = event.target.closest(".hero-mini-nav a");
  if (frameNavLink) {
    const topbar = frameNavLink.closest(".hero-topline, .frame-topline");
    topbar?.classList.remove("is-menu-open");
    topbar?.querySelector(".frame-menu-toggle")?.setAttribute("aria-expanded", "false");
  }

  const languageButton = event.target.closest(".language-switcher button");
  if (languageButton) {
    currentLang = languageButton.dataset.lang || "sr";
    applyLanguage();
    await ensureLanguageContent(currentLang);
    applyLanguage();
    return;
  }

  const inquiryToggle = event.target.closest(".inquiry-toggle");
  if (inquiryToggle) {
    openInquiryDialog(inquiryToggle.dataset.kitten || "");
    return;
  }

  const sliderButton = event.target.closest(".slider-button");
  if (sliderButton) {
    moveDetailSlider(sliderButton);
    return;
  }

  const card = event.target.closest(".animal-card");

  if (!card) return;

  if (card.dataset.page) {
    window.location.href = `${card.dataset.page}?id=${card.dataset.id}`;
    return;
  }

  const source = card.dataset.target === "#catsGrid" ? cats : kittens;
  openDetail(source[Number(card.dataset.index)]);
});

document.addEventListener("submit", (event) => {
  const contactForm = event.target.closest(".contact-form");
  if (contactForm) {
    event.preventDefault();
    submitContactForm(contactForm);
    return;
  }

  const form = event.target.closest(".inquiry-form");
  if (!form) return;
  event.preventDefault();
  submitInquiry(form);
});

