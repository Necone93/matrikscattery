function localizeItem(item) {
  const isPost = Object.prototype.hasOwnProperty.call(item, "title");
  const fallback = isPost ? postTranslationFallbacks[item.id]?.[currentLang] : animalTranslationFallbacks[item.id]?.[currentLang];
  const translated = item.translations?.[currentLang] || fallback;
  if (!translated) return item;

  const localized = {
    ...item,
    ...translated,
    facts: translated.facts || item.facts,
  };

  if (isPost) {
    localized.date = translated.date || translated.category || item.date;
    if (translated.text && !translated.blocks && Array.isArray(item.blocks) && item.blocks.length) {
      localized.blocks = [
        { type: "text", text: translated.text },
        ...item.blocks.filter((block) => block.type === "media"),
      ];
    }
  }

  return localized;
}

async function refreshContent() {
  try {
    const response = await fetch(`/api/content?ts=${Date.now()}`, { cache: "no-store" });
    if (!response.ok) return false;
    const data = await response.json();
    cats = data.cats || cats;
    kittens = data.kittens || kittens;
    posts = data.posts || posts;
    return true;
  } catch {
    return false;
  }
}

function contentHasLanguage(lang) {
  if (lang === "sr") return true;
  return [...cats, ...kittens, ...posts].some((item) => Object.keys(item.translations?.[lang] || {}).length > 0);
}

async function ensureLanguageContent(lang) {
  if (contentHasLanguage(lang)) return;
  await refreshContent();
  if (contentHasLanguage(lang)) return;

  translationRequests[lang] ||= fetch(`/api/translations/${lang}`, { method: "POST" })
    .then(async (response) => {
      const result = await response.json();
      if (!response.ok || !result.ok) throw new Error(result.error || "Prevod nije dostupan.");
      cats = result.content?.cats || cats;
      kittens = result.content?.kittens || kittens;
      posts = result.content?.posts || posts;
    })
    .catch((error) => {
      console.warn(error.message);
      return refreshContent();
    });

  await translationRequests[lang];
}

